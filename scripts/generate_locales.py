def load_android_app_name(lang):
    folder = "values" if lang == "en" else "values-" + lang
    path = os.path.join(ANDROID_RES, folder, "strings.xml")
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        text = f.read()
    match = re.search(r'<string name="app_name">(.*?)</string>', text, re.S)
    if not match:
        return None
    return (
        match.group(1)
        .replace("\\'", "'")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
        .replace("&quot;", '"')
    )


def load_arb(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    langs = ["en"] + [c for c in WEB_TO_ARB if c != "en"]
    catalogs = {lang: {} for lang in langs}
    if not os.path.isdir(ARB_DIR):
        raise SystemExit("ARB dir missing: " + ARB_DIR)

    loaded = 0
    for lang, arb_name in WEB_TO_ARB.items():
        path = os.path.join(ARB_DIR, arb_name)
        if not os.path.isfile(path):
            continue
        arb = load_arb(path)
        loaded += 1
        for dest, src in ARB_SEED.items():
            if src in arb and isinstance(arb[src], str):
                catalogs[lang][dest] = arb[src]

    # Plural variants are only written when a language has its own form.
    SPARSE = {
        "plants_count_two",
        "plants_count_few",
        "plants_count_many",
        "plants_count_zero",
    }

    for key, by_lang in NEW.items():
        en = by_lang["en"]
        for lang in langs:
            if lang in by_lang:
                catalogs[lang][key] = by_lang[lang]
            elif key not in SPARSE:
                catalogs[lang].setdefault(key, en)

    RANK_ALIASES = (
        ("family", "taxonomy_familia"),
        ("genus", "taxonomy_genus"),
    )
    for cat in catalogs.values():
        for short, long in RANK_ALIASES:
            if short in cat:
                cat.setdefault(long, cat[short])
            if long in cat:
                cat.setdefault(short, cat[long])

    # Keep About/Help and other keys already in locales.json that this
    # script does not generate (so a regenerate does not wipe them).
    if os.path.isfile(OUT):
        with open(OUT, encoding="utf-8") as handle:
            existing = json.load(handle)
        for lang, cat in catalogs.items():
            for key, val in (existing.get(lang) or {}).items():
                cat.setdefault(key, val)

    DROP_KEYS = {
        "about_fact_body",
        "about_langs_official",
        "about_langs_also",
        "about_langs_more",
    }
    for cat in catalogs.values():
        for key in DROP_KEYS:
            cat.pop(key, None)

    for lang in langs:
        name = load_android_app_name(lang)
        if name:
            catalogs[lang]["app_name"] = name

    # Ensure every key exists in every language
    master = set(catalogs["en"])
    for lang, cat in catalogs.items():
        for key in master:
            if key in SPARSE:
                continue
            cat.setdefault(key, catalogs["en"][key])

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(catalogs, f, ensure_ascii=False, indent=2)
        f.write("\n")

    missing = []
    for lang, cat in catalogs.items():
        for key, val in cat.items():
            if lang != "en" and val == catalogs["en"][key] and key not in ("store_play", "store_apple", "app_name"):
                missing.append(f"{lang}.{key}")
    print("arb", ARB_DIR, "files", loaded)
    print("wrote", OUT, "langs", len(catalogs), "keys", len(catalogs["en"]))
    leftover = [m for m in missing if not m.startswith("en.")]
    print("untranslated (fallback en)", len(leftover))


